@dataclass
class GuardrailConfig:
    """Configuration options for Stage 4 Semantic Fidelity Guardrail."""
    mode: str = "balanced"
    threshold: Optional[float] = None
    model_name: str = "sentence-transformers/all-MiniLM-L6-v2"
    cache_dir: Optional[str] = None
    max_retries: int = 2
    strict_preservation: bool = True
    device: str = "cpu"
    local_files_only: bool = True

    def __post_init__(self) -> None:
        valid_modes = {"conservative", "balanced", "aggressive"}
        if self.mode not in valid_modes:
            raise ValueError(
                f"Invalid optimization mode '{self.mode}'. Must be one of: {sorted(list(valid_modes))}"
            )
        if self.threshold is not None:
            if not isinstance(self.threshold, (int, float)) or not (0.0 < float(self.threshold) <= 1.0):
                raise ValueError(
                    f"Invalid threshold '{self.threshold}'. Must be a float strictly between 0.0 and 1.0."
                )
            self.threshold = float(self.threshold)
        else:
            self.threshold = MODE_THRESHOLDS[self.mode]

        if not isinstance(self.max_retries, int) or self.max_retries < 0:
            raise ValueError(f"max_retries must be a non-negative integer, got {self.max_retries}")


