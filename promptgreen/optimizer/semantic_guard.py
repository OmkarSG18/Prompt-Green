def compute_cosine_similarity(vec_a: Any, vec_b: Any) -> float:
    """
    Compute cosine similarity between two 1-D numerical vectors.
    Returns float in range [-1.0, 1.0].

    Explicitly guards against:
    - None inputs
    - Empty vectors
    - Dimension mismatches
    - NaN values
    - Positive or negative infinity
    - Zero vectors (norm == 0.0)
    - Invalid or non-finite dot products and norms

    Returns 0.0 safely on any invalid numerical input to prevent accidental acceptance.
    """
    if vec_a is None or vec_b is None:
        return 0.0
    try:
        a = np.asarray(vec_a, dtype=np.float32).flatten()
        b = np.asarray(vec_b, dtype=np.float32).flatten()
    except (ValueError, TypeError):
        return 0.0

    if a.size == 0 or b.size == 0 or a.shape != b.shape:
        return 0.0

    # Explicit check for NaN or Inf in vectors
    if not np.all(np.isfinite(a)) or not np.all(np.isfinite(b)):
        return 0.0

    norm_a = float(np.linalg.norm(a))
    norm_b = float(np.linalg.norm(b))
    if not np.isfinite(norm_a) or not np.isfinite(norm_b) or norm_a == 0.0 or norm_b == 0.0:
        return 0.0

    dot = float(np.dot(a, b))
    if not np.isfinite(dot):
        return 0.0

    sim = dot / (norm_a * norm_b)
    if not np.isfinite(sim):
        return 0.0

    return float(np.clip(sim, -1.0, 1.0))


class LocalMiniLMEmbedder:
    """
    CPU-first, offline-only embedding generator for 'all-MiniLM-L6-v2'.

    Supports:
    1. Direct sentence-transformers library if installed.
    2. Direct PyTorch + safetensors + tokenizers loader if cached snapshot is present on disk.
    3. Injected custom mock / client callable for deterministic unit tests.
    4. Deterministic sentence-aware chunked embedding for inputs exceeding 128 tokens.
    """

    def __init__(
        self,
        model_name: str = "sentence-transformers/all-MiniLM-L6-v2",
        cache_dir: Optional[str] = None,
        custom_client: Optional[Any] = None,
    ) -> None:
        self.model_name = model_name
        self.cache_dir = cache_dir
        self.custom_client = custom_client
        self._st_model: Optional[Any] = None
        self._pytorch_model: Optional[Any] = None
        self._tokenizer: Optional[Any] = None
        self._is_available: Optional[bool] = None
        self._status_message: str = "uninitialized"
        self._snapshot_dir: Optional[str] = None
        self.last_chunk_count: int = 1

    def _locate_cache_snapshot(self) -> Optional[str]:
        """Check the local Hugging Face hub cache for all-MiniLM-L6-v2."""
        search_dirs = []
        if self.cache_dir:
            search_dirs.append(Path(self.cache_dir))

        # Standard Hugging Face hub locations
        hf_home = os.environ.get("HF_HOME")
        if hf_home:
            search_dirs.append(Path(hf_home) / "hub")

        home = Path.home()
        search_dirs.append(home / ".cache" / "huggingface" / "hub")

        for sdir in search_dirs:
            if not sdir.exists():
                continue
            model_folder = sdir / "models--sentence-transformers--all-MiniLM-L6-v2"
            if model_folder.exists():
                snapshots = list((model_folder / "snapshots").glob("*"))
                if snapshots:
                    return str(snapshots[0])
        return None

    def initialize(self) -> bool:
        """
        Lazily initialize the embedding model without network requests.
        Returns True if model is ready for inference on CPU, False otherwise.
        """
        if self._is_available is not None:
            return self._is_available

        # 1. Custom mock / test client
        if self.custom_client is not None:
            self._is_available = True
            self._status_message = "initialized with custom client"
            return True

        snapshot_path = self._locate_cache_snapshot()
        self._snapshot_dir = snapshot_path

        # 2. Try official sentence_transformers library
        try:
            from sentence_transformers import SentenceTransformer  # type: ignore
            model_path = snapshot_path if snapshot_path else self.model_name
            self._st_model = SentenceTransformer(
                model_path,
                device="cpu",
                local_files_only=True
            )
            self._is_available = True
            self._status_message = "loaded via sentence_transformers (offline)"
            return True
        except ImportError:
            pass
        except Exception as exc:
            logger.debug(f"sentence_transformers load failed: {exc}")

        # 3. Direct PyTorch + Safetensors + Tokenizers fallback
        if snapshot_path:
            try:
                import torch
                import safetensors.torch
                from tokenizers import Tokenizer  # type: ignore

                tok_file = os.path.join(snapshot_path, "tokenizer.json")
                weights_file = os.path.join(snapshot_path, "model.safetensors")
                cfg_file = os.path.join(snapshot_path, "config.json")

                if os.path.exists(tok_file) and os.path.exists(weights_file) and os.path.exists(cfg_file):
                    self._tokenizer = Tokenizer.from_file(tok_file)
                    weights = safetensors.torch.load_file(weights_file)
                    with open(cfg_file, "r", encoding="utf-8") as f:
                        cfg = json.load(f)

                    # Build lightweight PyTorch Bert model wrapper
                    self._pytorch_model = _build_minilm_pytorch_module(cfg, weights)
                    self._is_available = True
                    self._status_message = "loaded via direct PyTorch + safetensors (offline)"
                    return True
            except Exception as exc:
                self._status_message = f"Direct PyTorch model load failed: {exc}"

        # 4. If all fail, mark unavailable with exact reason
        if not snapshot_path:
            self._status_message = (
                f"Local model cache for '{self.model_name}' not found. "
                "Offline operation prohibits remote downloading."
            )
        else:
            self._status_message = (
                "sentence_transformers library is not installed in the active Python environment, "
                "and PyTorch fallback initialization was unsuccessful."
            )

        self._is_available = False
        return False

    @property
    def is_available(self) -> bool:
        if self._is_available is None:
            return self.initialize()
        return self._is_available

    @property
    def status_message(self) -> str:
        return self._status_message

    def chunk_text(self, text: str, max_words_per_chunk: int = 70) -> List[str]:
        """
        Split text into sentence-aware chunks fitting comfortably within the 128-token limit.
        Handles long single sentences by sub-slicing words.
        Safe against empty input and whitespace-only chunks.
        Bounded to a maximum of 100 chunks to prevent unbounded execution.
        """
        text = text.strip()
        if not text:
            return []

        # Split along sentence or newline boundaries
        sentences = [s.strip() for s in re.split(r"(?<=[.!?;\n])\s+", text) if s.strip()]
        if not sentences:
            sentences = [text]

        chunks: List[str] = []
        current_chunk: List[str] = []
        current_len = 0
        max_chunks = 100

        for sent in sentences:
            words = sent.split()
            if not words:
                continue

            if len(words) > max_words_per_chunk:
                # Long sentence exceeds chunk limit: flush current and sub-slice
                if current_chunk:
                    chunks.append(" ".join(current_chunk))
                    current_chunk = []
                    current_len = 0
                for i in range(0, len(words), max_words_per_chunk):
                    if len(chunks) >= max_chunks:
                        break
                    chunks.append(" ".join(words[i : i + max_words_per_chunk]))
            else:
                if current_len + len(words) > max_words_per_chunk and current_chunk:
                    chunks.append(" ".join(current_chunk))
                    current_chunk = [sent]
                    current_len = len(words)
                else:
                    current_chunk.append(sent)
                    current_len += len(words)

            if len(chunks) >= max_chunks:
                break

        if current_chunk and len(chunks) < max_chunks:
            chunks.append(" ".join(current_chunk))

        return chunks

    def _encode_single_chunk(self, chunk: str) -> Tuple[np.ndarray, float]:
        """Encode a single chunk of text and return (unit_vector, token_weight)."""
        if not chunk or not chunk.strip():
            return np.zeros(384, dtype=np.float32), 0.0

        # Custom mock client
        if self.custom_client is not None:
            res = self.custom_client(chunk)
            arr = np.asarray(res, dtype=np.float32).flatten()
            norm = float(np.linalg.norm(arr))
            if norm > 0 and np.isfinite(norm):
                arr = arr / norm
            return arr, float(max(1, len(chunk.split())))

        # sentence_transformers library
        if self._st_model is not None:
            vec = self._st_model.encode(chunk, convert_to_numpy=True, normalize_embeddings=True)
            arr = np.asarray(vec, dtype=np.float32).flatten()
            return arr, float(max(1, len(chunk.split())))

        # Direct PyTorch forward pass
        if self._pytorch_model is not None and self._tokenizer is not None:
            import torch
            with torch.no_grad():
                enc = self._tokenizer.encode(chunk)
                input_ids = torch.tensor([enc.ids], dtype=torch.long)
                attention_mask = torch.tensor([enc.attention_mask], dtype=torch.float32)
                vec = self._pytorch_model(input_ids, attention_mask)
                arr = vec.cpu().numpy().flatten()
                weight = float(sum(enc.attention_mask))
                return arr, max(weight, 1.0)

        raise RuntimeError("Embedding engine encountered an uninitialized execution branch.")

    def embed(self, text: str) -> np.ndarray:
        """
        Generate 384-dimensional dense embedding vector for text.
        For inputs exceeding single-chunk limits, uses sentence-aware chunking
        and token-weighted mean aggregation with L2 normalization.
        Raises RuntimeError if model is unavailable.
        """
        if not self.is_available:
            raise RuntimeError(f"Embedding model unavailable: {self._status_message}")

        if not text or not text.strip():
            self.last_chunk_count = 0
            return np.zeros(384, dtype=np.float32)

        chunks = self.chunk_text(text)
        if not chunks:
            self.last_chunk_count = 0
            return np.zeros(384, dtype=np.float32)

        self.last_chunk_count = len(chunks)

        # Optimization: single chunk fast-path
        if len(chunks) == 1:
            vec, _ = self._encode_single_chunk(chunks[0])
            norm = float(np.linalg.norm(vec))
            if norm > 0 and np.isfinite(norm):
                vec = vec / norm
            return vec

        # Multi-chunk token-weighted mean aggregation
        chunk_vecs: List[np.ndarray] = []
        chunk_weights: List[float] = []

        for c in chunks:
            cv, cw = self._encode_single_chunk(c)
            chunk_vecs.append(cv)
            chunk_weights.append(cw)

        total_weight = sum(chunk_weights)
        if total_weight <= 0.0:
            total_weight = 1.0

        agg = np.zeros(384, dtype=np.float32)
        for cv, cw in zip(chunk_vecs, chunk_weights):
            agg += (cw / total_weight) * cv

        norm = float(np.linalg.norm(agg))
        if norm > 0.0 and np.isfinite(norm):
            agg = agg / norm
        else:
            agg = np.zeros(384, dtype=np.float32)

        return agg

    def embed_chunks(self, text: str) -> List[Tuple[np.ndarray, str]]:
        """Return list of (chunk_vector, chunk_text) for localized chunk diagnostics."""
        if not self.is_available:
            raise RuntimeError(f"Embedding model unavailable: {self._status_message}")
        chunks = self.chunk_text(text)
        results: List[Tuple[np.ndarray, str]] = []
        for c in chunks:
            v, _ = self._encode_single_chunk(c)
            norm = float(np.linalg.norm(v))
            if norm > 0 and np.isfinite(norm):
                v = v / norm
            results.append((v, c))
        return results


def _build_minilm_pytorch_module(config: Dict[str, Any], weights: Dict[str, Any]) -> Any:
    """Helper creating a minimal PyTorch forward pass for all-MiniLM-L6-v2."""
    import torch
    import torch.nn as nn
    import torch.nn.functional as F

    class _MiniLMEngine(nn.Module):
        def __init__(self, cfg: Dict[str, Any], w: Dict[str, Any]):
            super().__init__()
            self.hidden_size = cfg.get("hidden_size", 384)
            self.num_layers = cfg.get("num_hidden_layers", 6)
            self.num_heads = cfg.get("num_attention_heads", 12)
            self.head_dim = self.hidden_size // self.num_heads
            self.weights = w

        def forward(self, input_ids: torch.Tensor, attention_mask: torch.Tensor) -> torch.Tensor:
            seq_len = input_ids.shape[1]
            pos_ids = torch.arange(seq_len, dtype=torch.long, device=input_ids.device).unsqueeze(0)
            tok_type_ids = torch.zeros_like(input_ids)

            w_emb = F.embedding(input_ids, self.weights["embeddings.word_embeddings.weight"])
            p_emb = F.embedding(pos_ids, self.weights["embeddings.position_embeddings.weight"])
            t_emb = F.embedding(tok_type_ids, self.weights["embeddings.token_type_embeddings.weight"])

            hidden = w_emb + p_emb + t_emb
            hidden = F.layer_norm(
                hidden,
                (self.hidden_size,),
                self.weights["embeddings.LayerNorm.weight"],
                self.weights["embeddings.LayerNorm.bias"],
                1e-12
            )

            ext_mask = (1.0 - attention_mask)[:, None, None, :] * -10000.0

            for l in range(self.num_layers):
                pfx = f"encoder.layer.{l}."
                B, S, H = hidden.shape
                q = F.linear(hidden, self.weights[pfx + "attention.self.query.weight"], self.weights[pfx + "attention.self.query.bias"])
                k = F.linear(hidden, self.weights[pfx + "attention.self.key.weight"], self.weights[pfx + "attention.self.key.bias"])
                v = F.linear(hidden, self.weights[pfx + "attention.self.value.weight"], self.weights[pfx + "attention.self.value.bias"])

                q = q.view(B, S, self.num_heads, self.head_dim).transpose(1, 2)
                k = k.view(B, S, self.num_heads, self.head_dim).transpose(1, 2)
                v = v.view(B, S, self.num_heads, self.head_dim).transpose(1, 2)

                scores = torch.matmul(q, k.transpose(-1, -2)) / (self.head_dim ** 0.5)
                scores = scores + ext_mask
                probs = F.softmax(scores, dim=-1)
                ctx = torch.matmul(probs, v).transpose(1, 2).contiguous().view(B, S, H)

                attn_out = F.linear(ctx, self.weights[pfx + "attention.output.dense.weight"], self.weights[pfx + "attention.output.dense.bias"])
                hidden = F.layer_norm(
                    hidden + attn_out,
                    (self.hidden_size,),
                    self.weights[pfx + "attention.output.LayerNorm.weight"],
                    self.weights[pfx + "attention.output.LayerNorm.bias"],
                    1e-12
                )

                inter = F.gelu(F.linear(hidden, self.weights[pfx + "intermediate.dense.weight"], self.weights[pfx + "intermediate.dense.bias"]))
                ffn_out = F.linear(inter, self.weights[pfx + "output.dense.weight"], self.weights[pfx + "output.dense.bias"])
                hidden = F.layer_norm(
                    hidden + ffn_out,
                    (self.hidden_size,),
                    self.weights[pfx + "output.LayerNorm.weight"],
                    self.weights[pfx + "output.LayerNorm.bias"],
                    1e-12
                )

            # Mean pooling
            mask_exp = attention_mask.unsqueeze(-1)
            sum_emb = torch.sum(hidden * mask_exp, dim=1)
            sum_mask = torch.clamp(mask_exp.sum(dim=1), min=1e-9)
            mean_pooled = sum_emb / sum_mask
            return F.normalize(mean_pooled, p=2, dim=1)

    return _MiniLMEngine(config, weights)


class SemanticFidelityGuard:
    """
    Stage 4 Semantic Fidelity Guardrail.

    Validates cosine similarity and critical instruction preservation between
    the original input prompt and optimized candidates across pipeline stages.
    """

    def __init__(
        self,
        config: Optional[GuardrailConfig] = None,
        embedder: Optional[LocalMiniLMEmbedder] = None,
    ) -> None:
        self.config = config or GuardrailConfig()
        self.embedder = embedder or LocalMiniLMEmbedder(
            model_name=self.config.model_name,
            cache_dir=self.config.cache_dir
        )

    # -------------------------------------------------------------------------
    # Core Prompt & Directive Disambiguation (Task 4)
    # -------------------------------------------------------------------------

    def _extract_core_and_directives(self, text: str) -> Tuple[str, List[str]]:
        """
        Isolate core prompt content from recognized Stage 3 output formatting directives.
        Returns (core_prompt, list_of_detected_directives).
        """
        remaining = text
        directives_found: List[str] = []
        for pat in STAGE3_DIRECTIVE_PATTERNS:
            m = re.search(pat, remaining, re.IGNORECASE)
            if m:
                directives_found.append(m.group(0).strip())
                remaining = re.sub(pat, "", remaining, count=1, flags=re.IGNORECASE)

        core = re.sub(r"\s+", " ", remaining).strip().strip(".:;, ")
        if core:
            core += "."
        return core, directives_found

    # -------------------------------------------------------------------------
    # Critical Instruction and Structural Preservation Validation (Task 2)
    # -------------------------------------------------------------------------

    def verify_preservation(self, original: str, candidate: str) -> Tuple[bool, List[str]]:
        """
        Verify that candidate strictly preserves all critical instruction elements:
        - Negations multiplicity and polarity invariance ("must not delete A")
        - Numerical constraints, decimals, units, comparison operators (<, >, <=, >=)
        - Conditions and exception predicates ("if unavailable", "except protected files")
        - JSON keys and schemas ("keys", "fields", "attributes", raw JSON keys)
        - URLs and file paths
        - Technical programming identifiers
        - Code blocks
        - Required output format directives (preventing format inversion e.g. "never use a table")
        """
        violations: List[str] = []
        if not candidate or not candidate.strip():
            violations.append("Candidate prompt is empty or blank.")
            return False, violations

        orig_lower = original.lower()
        cand_lower = candidate.lower()

        # 1. Negations Preservation & Multiplicity
        for pat in NEGATION_PATTERNS:
            orig_matches = list(re.finditer(pat, orig_lower))
            if orig_matches:
                cand_matches = list(re.finditer(pat, cand_lower))
                if len(cand_matches) < len(orig_matches):
                    clean_kw = pat.replace(r"\b", "").replace(r"\s+", " ").replace(r"\'?", "").replace("'", "")
                    violations.append(
                        f"Missing mandatory negation '{clean_kw}' present in original (found {len(cand_matches)}, expected {len(orig_matches)})."
                    )

        # 1b. Polarity Inversion & Negation Binding Check
        neg_clause_pattern = r"\b(must not|do not|don'?t|never|cannot|can'?t|won'?t|not)\s+([a-zA-Z0-9_-]+(?:\s+[a-zA-Z0-9_-]+)?)\b"
        orig_neg_clauses = re.findall(neg_clause_pattern, orig_lower)
        for neg, target in orig_neg_clauses:
            full_neg = f"{neg} {target}"
            if full_neg not in cand_lower:
                # Check if target appears unnegated in candidate (not immediately preceded by negation)
                if re.search(rf"(?<!not\s)(?<!never\s)(?<!don't\s)(?<!do not\s)\b{re.escape(target)}\b", cand_lower):
                    violations.append(
                        f"Polarity inversion detected: '{target}' was negated in original as '{full_neg}' but appears unnegated in candidate."
                    )

        # 2. Conditions and Exceptions Multiplicity
        for pat in CONDITIONAL_PATTERNS:
            orig_matches = list(re.finditer(pat, orig_lower))
            if orig_matches:
                cand_matches = list(re.finditer(pat, cand_lower))
                if len(cand_matches) < len(orig_matches):
                    clean_kw = pat.replace(r"\b", "").replace(r"\s+", " ")
                    violations.append(f"Missing conditional/exception indicator '{clean_kw}'.")

        # 2b. Condition Predicate Preservation (e.g. 'If database is unavailable, do not retry')
        for m in re.finditer(r"\b(?:if|unless|whenever)\s+([^,.;\n]+)", orig_lower):
            cond_text = m.group(1).strip()
            words = [w for w in re.findall(r"\b[a-z]{3,}\b", cond_text) if w not in {"the", "and", "for", "with", "this", "that"}]
            missing_words = [w for w in words if w not in cand_lower]
            if words and len(missing_words) > len(words) // 2:
                violations.append(f"Condition context removed: predicate for 'if {cond_text}' missing key terms: {missing_words}.")

        # 2c. Exception Clause Preservation (e.g. 'except protected files')
        for m in re.finditer(r"\b(?:except|excluding|without)\s+([^,.;\n]+)", orig_lower):
            exc_text = m.group(1).strip()
            words = [w for w in re.findall(r"\b[a-z]{3,}\b", exc_text) if w not in {"the", "and", "for", "with", "this", "that"}]
            missing_words = [w for w in words if w not in cand_lower]
            if missing_words:
                violations.append(f"Exception clause removed: 'except {exc_text}' missing key terms: {missing_words}.")

        # 3. Numerical Constraints, Units, Operators, and Ranges
        # Comparison operators with numbers (e.g. "< 50ms", "<= 256mb")
        num_constraints = re.findall(
            r"(?:<=|>=|<|>|==|!=)?\s*\b\d+(?:\.\d+)?(?:ms|s|sec|min|h|hr|kb|mb|gb|tb|%|x|px|rem|em|pt|kg|g|mg|m|cm|mm|v|w|kw|hz|khz|mhz|ghz)?\b",
            orig_lower
        )
        for nc in num_constraints:
            clean_nc = nc.strip()
            if clean_nc and clean_nc not in cand_lower:
                violations.append(f"Missing numerical constraint/unit '{clean_nc}' present in original.")

        # Numerical ranges (e.g. "10 to 20", "10-20")
        ranges = re.findall(r"\b\d+\s*(?:-|to)\s*\d+\b", original, re.IGNORECASE)
        for rng in ranges:
            clean_rng = re.sub(r"\s+", " ", rng).strip().lower()
            if clean_rng not in cand_lower and rng.lower() not in cand_lower:
                violations.append(f"Missing numerical range constraint '{rng}' present in original.")

        # 4. URLs Preservation
        urls = re.findall(r"https?://[^\s\"'<>]+", original)
        for u in urls:
            if u not in candidate:
                violations.append(f"Missing URL '{u}' present in original.")

        # 5. File Paths Preservation
        paths = re.findall(r"(?:/[a-zA-Z0-9_.-]+)+/[a-zA-Z0-9_.-]+|[A-Za-z]:\\[a-zA-Z0-9_.\\]+", original)
        for p in paths:
            if p not in candidate:
                violations.append(f"Missing file path '{p}' present in original.")

        # 6. Technical Identifiers (e.g. ERR_CONNECTION_REFUSED, max_connections)
        idents = re.findall(r"\b[A-Z0-9_]{3,}\b|\b[a-z]+_[a-z0-9_]+\b", original)
        for ident in idents:
            if ident.lower() in {"and", "the", "for", "with", "from", "json", "yaml", "html", "xml"}:
                continue
            if ident not in candidate and ident.lower() not in cand_lower:
                violations.append(f"Missing technical identifier '{ident}' present in original.")

        # 7. Exact JSON Keys, Schemas, and Fields
        m_keys = re.search(r"\b(?:keys?|fields?|attributes?|properties)\s*(?::|are|include)?\s*([a-zA-Z0-9_,\s]+)", orig_lower)
        if m_keys:
            raw_keys = re.split(r"(?:,\s*|\s+and\s+|\s+or\s+|\s+)", m_keys.group(1).strip())
            for k in raw_keys:
                k = k.strip()
                if k and len(k) > 1 and k not in cand_lower:
                    violations.append(f"Missing required JSON key/field '{k}' present in original.")

        raw_json_keys = re.findall(r'"([a-zA-Z0-9_]+)"\s*:', original)
        for rk in raw_json_keys:
            if rk not in candidate and rk.lower() not in cand_lower:
                violations.append(f"Missing raw JSON schema key '{rk}' present in original.")

        # 8. Markdown Fenced Code Blocks & Inline Code
        code_blocks = re.findall(r"```[\s\S]*?```", original)
        for cb in code_blocks:
            if cb not in candidate:
                violations.append("Fenced code block present in original was altered or removed.")

        inline_code = re.findall(r"`[^`\n]+`", original)
        for ic in inline_code:
            if ic not in candidate and ic.strip("`") not in candidate:
                violations.append(f"Inline code identifier '{ic}' present in original was altered or removed.")

        # 9. Format Directive Inversion & Negation
        for fmt, patterns in FORMAT_INDICATORS.items():
            in_orig = any(re.search(p, orig_lower) for p in patterns)
            if in_orig:
                # Must be present in candidate
                in_cand = any(re.search(p, cand_lower) for p in patterns)
                if not in_cand:
                    violations.append(f"Required output format '{fmt}' present in original was omitted.")
                # Candidate must not explicitly negate the format
                neg_fmt_patterns = [
                    rf"\b(?:never|do not|don'?t|must not|avoid|without)\s+[^.!?;\n]*?\b{re.escape(fmt)}\b",
                    rf"\bno\s+{re.escape(fmt)}\b"
                ]
                for nfp in neg_fmt_patterns:
                    if re.search(nfp, cand_lower):
                        violations.append(f"Output format inversion: candidate explicitly negates required format '{fmt}'.")

        return (len(violations) == 0, violations)

    # -------------------------------------------------------------------------
    # Core Evaluation Interface
    # -------------------------------------------------------------------------

    def evaluate(
        self,
        original_prompt: str,
        candidate_prompt: str,
        retry_callback: Optional[Callable[[str, int], str]] = None,
        intermediate_stages: Optional[Dict[str, str]] = None,
    ) -> GuardrailResult:
        """
        Evaluate candidate prompt semantic similarity and instruction preservation.

        Args:
            original_prompt: Raw user input prompt.
            candidate_prompt: Output produced by prior optimization stage(s).
            retry_callback: Optional callable(mode, retry_index) -> new_candidate.
            intermediate_stages: Optional dict of prior stages for comparative analysis.

        Returns:
            GuardrailResult containing similarity score, pass/fail, and final prompt.
        """
        start_time = time.perf_counter()
        failure_reasons: List[str] = []
        active_threshold = self.config.threshold or MODE_THRESHOLDS[self.config.mode]
        current_mode = self.config.mode

        # Handle empty original prompt
        if not original_prompt or not original_prompt.strip():
            latency = (time.perf_counter() - start_time) * 1000.0
            return GuardrailResult(
                original_prompt=original_prompt,
                candidate_prompt=candidate_prompt,
                final_prompt=original_prompt,
                passed=True,
                similarity_score=1.0,
                active_threshold=active_threshold,
                selected_mode=current_mode,
                final_mode=current_mode,
                retry_count=0,
                rollback_occurred=False,
                rollback_stage="none",
                guardrail_latency_ms=round(latency, 2),
                model_status="bypassed for empty prompt",
            )

        # Step 1: Check embedding model availability
        emb_start = time.perf_counter()
        model_ready = self.embedder.is_available
        emb_latency_ms = 0.0

        if not model_ready:
            failure_reasons.append(
                f"Embedding model unavailable ({self.embedder.status_message}); "
                "cannot verify semantic fidelity. Failing safely to original prompt."
            )
            total_latency = (time.perf_counter() - start_time) * 1000.0
            return GuardrailResult(
                original_prompt=original_prompt,
                candidate_prompt=candidate_prompt,
                final_prompt=original_prompt,
                passed=False,
                similarity_score=None,
                active_threshold=active_threshold,
                selected_mode=self.config.mode,
                final_mode=current_mode,
                retry_count=0,
                rollback_occurred=True,
                rollback_stage="original",
                failure_reasons=failure_reasons,
                guardrail_latency_ms=round(total_latency, 2),
                model_available=False,
                model_status=self.embedder.status_message,
            )

        # Generate original prompt embedding (supports chunking)
        try:
            orig_emb = self.embedder.embed(original_prompt)
            # Ensure finite
            if not np.all(np.isfinite(orig_emb)):
                raise ValueError("Original embedding contains NaN or Inf.")
        except Exception as exc:
            emb_latency_ms = (time.perf_counter() - emb_start) * 1000.0
            failure_reasons.append(f"Embedding generation error on original prompt: {exc}")
            total_latency = (time.perf_counter() - start_time) * 1000.0
            return GuardrailResult(
                original_prompt=original_prompt,
                candidate_prompt=candidate_prompt,
                final_prompt=original_prompt,
                passed=False,
                similarity_score=None,
                active_threshold=active_threshold,
                selected_mode=self.config.mode,
                final_mode=current_mode,
                retry_count=0,
                rollback_occurred=True,
                rollback_stage="original",
                failure_reasons=failure_reasons,
                embedding_latency_ms=round(emb_latency_ms, 2),
                guardrail_latency_ms=round(total_latency, 2),
                model_available=True,
                model_status=f"error: {exc}",
            )

        # Intermediate stage comparisons if provided
        stage_sims: Dict[str, float] = {}
        if intermediate_stages:
            for sname, sprompt in intermediate_stages.items():
                if sprompt and sprompt.strip():
                    try:
                        s_emb = self.embedder.embed(sprompt)
                        sim_val = compute_cosine_similarity(orig_emb, s_emb)
                        stage_sims[sname] = round(float(sim_val), 4)
                    except Exception:
                        pass

        # Step 2: Evaluation and Bounded Retry Loop
        current_candidate = candidate_prompt
        retries_used = 0
        accepted = False
        similarity_score: Optional[float] = None
        core_similarity: Optional[float] = None
        disambiguation_applied = False
        preservation_violations: List[str] = []
        chunk_sims: List[float] = []

        mode_relaxation_chain = {
            "aggressive": "balanced",
            "balanced": "conservative",
            "conservative": None,
        }

        while True:
            # 1. Structural & Instruction Preservation
            p_ok, p_violations = self.verify_preservation(original_prompt, current_candidate)
            preservation_violations = p_violations

            # 2. Candidate Embedding & Cosine Similarity
            t_cand_start = time.perf_counter()
            try:
                cand_emb = self.embedder.embed(current_candidate)
                if not np.all(np.isfinite(cand_emb)):
                    raise ValueError("Candidate embedding contains NaN or Inf.")
                sim = compute_cosine_similarity(orig_emb, cand_emb)
                sim_finite = float(sim) if np.isfinite(sim) else 0.0
                similarity_score = round(sim_finite, 4)
                emb_latency_ms += (time.perf_counter() - t_cand_start) * 1000.0
            except Exception as exc:
                emb_latency_ms += (time.perf_counter() - t_cand_start) * 1000.0
                failure_reasons.append(f"Embedding error on candidate prompt: {exc}")
                similarity_score = 0.0
                p_ok = False

            # Multi-chunk diagnostic tracking
            chunk_sims = []
            if self.embedder.last_chunk_count > 1:
                try:
                    orig_chunks = self.embedder.embed_chunks(original_prompt)
                    cand_chunks = self.embedder.embed_chunks(current_candidate)
                    if len(orig_chunks) == len(cand_chunks):
                        for (ov, _), (cv, _) in zip(orig_chunks, cand_chunks):
                            chunk_sims.append(round(compute_cosine_similarity(ov, cv), 4))
                except Exception:
                    pass

            # 3. Decision Gate: Passes threshold AND preserves all instructions
            passed_threshold = (
                similarity_score is not None and similarity_score >= active_threshold
            )

            # TASK 4: Directive Disambiguation for Short Prompts
            # If candidate raw similarity is below threshold, check if added Stage 3 directives
            # caused dilution of a short prompt while the core prompt task remains preserved.
            if not passed_threshold and p_ok and similarity_score is not None:
                cand_core, directives_found = self._extract_core_and_directives(current_candidate)
                if directives_found and cand_core and cand_core != current_candidate:
                    try:
                        core_emb = self.embedder.embed(cand_core)
                        sim_c = compute_cosine_similarity(orig_emb, core_emb)
                        sim_c_finite = float(sim_c) if np.isfinite(sim_c) else 0.0
                        core_similarity = round(sim_c_finite, 4)

                        # Core task must strictly satisfy threshold (e.g. >= 0.92)
                        # and raw prompt must have non-trivial correlation (>= 0.70)
                        if core_similarity >= active_threshold and similarity_score >= 0.70:
                            passed_threshold = True
                            disambiguation_applied = True
                            similarity_score = core_similarity
                    except Exception as disc_exc:
                        logger.debug(f"Directive disambiguation calculation error: {disc_exc}")

            accepted = p_ok and passed_threshold

            if accepted:
                break

            # If not accepted, record failure reason for this candidate
            if not p_ok:
                failure_reasons.extend(p_violations)
            if similarity_score is not None and not passed_threshold:
                failure_reasons.append(
                    f"Cosine similarity ({similarity_score:.4f}) below active threshold ({active_threshold:.2f})."
                )

            # Check if retry is possible
            if retry_callback is not None and retries_used < self.config.max_retries:
                next_mode = mode_relaxation_chain.get(current_mode)
                if next_mode is not None:
                    retries_used += 1
                    current_mode = next_mode
                    active_threshold = MODE_THRESHOLDS[current_mode]
                    try:
                        current_candidate = retry_callback(current_mode, retries_used)
                        continue
                    except Exception as retry_exc:
                        failure_reasons.append(f"Retry callback execution failed: {retry_exc}")
                        break
            # Retries exhausted or no callback available
            break

        # Step 3: Final prompt determination & Rollback
        if accepted:
            final_prompt = current_candidate
            rollback_occurred = False
            rollback_stage = "none"
        else:
            final_prompt = original_prompt
            rollback_occurred = True
            rollback_stage = "original"
            failure_reasons.append("Semantic fidelity guard rejected candidate; safely rolled back to original prompt.")

        total_latency_ms = (time.perf_counter() - start_time) * 1000.0

        return GuardrailResult(
            original_prompt=original_prompt,
            candidate_prompt=candidate_prompt,
            final_prompt=final_prompt,
            passed=accepted,
            similarity_score=similarity_score,
            active_threshold=active_threshold,
            selected_mode=self.config.mode,
            final_mode=current_mode,
            retry_count=retries_used,
            rollback_occurred=rollback_occurred,
            rollback_stage=rollback_stage,
            failure_reasons=failure_reasons,
            preservation_violations=preservation_violations,
            embedding_latency_ms=round(emb_latency_ms, 2),
            guardrail_latency_ms=round(total_latency_ms, 2),
            model_available=True,
            model_status="ready",
            stage_similarities=stage_sims,
            chunk_similarities=chunk_sims,
            directive_disambiguation_applied=disambiguation_applied,
            core_similarity=core_similarity,
        )
