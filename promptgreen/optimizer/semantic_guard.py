"""
PromptGreen v2.0 - Semantic Fidelity Guardrail (Stage 4)
Dense Embedding Cosine Similarity Evaluation and Critical Instruction Preservation.

This module implements the Stage 4 guardrail for the PromptGreen v2.0 pipeline.
It verifies that candidate prompts generated by earlier stages (Pruner, Compressor,
Shaper) preserve the semantic meaning, critical instructions, negations, numerical
constraints, and format requirements of the original user prompt.

If a candidate falls below the configured cosine similarity threshold or violates
any critical instruction preservation check, an adaptive relaxation retry loop is
engaged. If retries are exhausted or fail, the guardrail safely rolls back to the
original prompt (or a safe prior stage) without data loss or semantic deflection.
"""

